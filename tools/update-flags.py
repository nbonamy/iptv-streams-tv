#!/usr/bin/env python3
"""Bundle flag-icons v7.6.0 as native TV artwork. Requires rsvg-convert."""
from pathlib import Path
import io
import re
import subprocess
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
VERSION = "7.6.0"
URL = f"https://codeload.github.com/lipis/flag-icons/tar.gz/refs/tags/v{VERSION}"
source = ROOT / "branding" / "flags"
output = ROOT / "app/src/main/res/drawable-nodpi"
source.mkdir(parents=True, exist_ok=True)
output.mkdir(parents=True, exist_ok=True)
with urllib.request.urlopen(URL, timeout=60) as response:
    archive = response.read()
codes = []
with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as archive:
    for member in archive.getmembers():
        match = re.search(r"/flags/4x3/([a-z]{2})\.svg$", member.name)
        if match:
            code = match.group(1)
            svg = source / f"{code}.svg"
            svg.write_bytes(archive.extractfile(member).read())
            subprocess.run(["rsvg-convert", "--width", "160", "--height", "120", str(svg), "-o", str(output / f"flag_{code}.png")], check=True)
            codes.append(code)
        elif member.name == f"flag-icons-{VERSION}/LICENSE":
            (ROOT / "licenses/flag-icons-MIT.txt").write_bytes(archive.extractfile(member).read())
mapping = ",\n".join(f'        "{code.upper()}" to R.drawable.flag_{code}' for code in sorted(codes))
(ROOT / "app/src/main/java/fr/bonamy/iptv/CountryFlags.kt").write_text(
    "// Generated by tools/update-flags.py from flag-icons v" + VERSION + ".\n"
    "package fr.bonamy.iptv\n\ninternal object CountryFlags {\n"
    "    val resources: Map<String, Int> = mapOf(\n" + mapping + "\n    )\n}\n"
)
print(f"Bundled {len(codes)} flag-icons v{VERSION} flags.")
